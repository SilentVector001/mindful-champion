async function main() {
  console.log('🏓 Seeding REAL tournaments with December 2025+ dates...\n')

  // Clear existing tournaments
  const deleteCount = await prisma.tournament.deleteMany({})
  console.log(`Deleted ${deleteCount.count} existing tournaments`)

  // Create new tournaments
  for (const tournament of REAL_TOURNAMENTS) {
    const created = await prisma.tournament.create({
      data: tournament,
    })
    console.log(`✅ Created: ${created.name} - ${created.city}, ${created.state} (${tournament.startDate.toLocaleDateString()})`)
  }

  console.log(`\n🎉 Successfully seeded ${REAL_TOURNAMENTS.length} tournaments!`)
}

main()
  .catch((e) => {
    console.error('Error seeding tournaments:', e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })

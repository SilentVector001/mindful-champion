// Helper functions
export function getDrillsByCategory(category: DrillCategory): Drill[] {
  return drillsDatabase.filter(drill => drill.category === category)
}

export function getDrillsByDifficulty(difficulty: DrillDifficulty): Drill[] {
  return drillsDatabase.filter(drill => drill.difficulty === difficulty)
}

export function getDrillsByContext(context: DrillContext): Drill[] {
  return drillsDatabase.filter(drill => drill.context.includes(context))
}

export function searchDrills(query: string): Drill[] {
  const lowerQuery = query.toLowerCase()
  return drillsDatabase.filter(drill => 
    drill.name.toLowerCase().includes(lowerQuery) ||
    drill.description.toLowerCase().includes(lowerQuery) ||
    drill.focusAreas.some(area => area.toLowerCase().includes(lowerQuery)) ||
    drill.category.toLowerCase().includes(lowerQuery)
  )
}

export function getDrillById(id: string): Drill | undefined {
  return drillsDatabase.find(drill => drill.id === id)
}

export function getRelatedDrills(drillId: string): Drill[] {
  const drill = getDrillById(drillId)
  if (!drill) return []
  
  const relatedIds = [
    ...(drill.relatedDrills || []),
    drill.easierVersion,
    drill.harderVersion
  ].filter(Boolean) as string[]
  
  return relatedIds.map(id => getDrillById(id)).filter(Boolean) as Drill[]
}

